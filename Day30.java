public class Day30 {
    public static void main(String[] args) {
        // Deklarasi
        int a = 10;
        int b = 20;

        // Operator perbandingan <=
        System.out.println("Operator perbandingan <=");
        System.out.println("Hasil True\t: " + (a <= b));
        System.out.println("Hasil False\t: " + (b <= a));
        
        // Operator perbandingan =>
        System.out.println("\nOperator perbandingan =>");
        System.out.println("Hasil True\t: " + (b >= a));
        System.out.println("Hasil False\t: " + (a >= b));
    }
}
