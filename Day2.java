public class biodata {
    public static void main(String[] args) {
        // Biodata Diri //
        String nama = "Arul Evansyah";
        int umur = 19;
        String alamat = "Kalukku";
        double tinggi = 160.0;
        

        // Menggunakan println() //
        System.out.println("==== Biodata Diri ====");

        // Menggunakan print() //
        System.out.print("Nama : ");
        System.out.print("Arul Evansyah");
        System.out.println();

        // Menggunakan printf() //
        System.out.printf("Umur : %d tahun%n", 19);
        System.out.printf("Alamat : %s%n", "Kalukku");
        System.out.printf("Tinggi : %d cm%n", 160);
        
    }
}
