public class Day5 {
    public static void main(String[] args) {
        
        /**
         * Day 5 - Deklarasikan Tipe Data Pecahan
         * Soal 1 : Mendeklarasikan berat dan tinggi.
         */

        // Berat badan menggunakan tipe data float
        float beratBadan = 55.5f;

        // Tinggi badan menggunakan tipe data double
        double tinggiBadan = 160.25;

        // Mencetak berat badan menggunakan printf
        System.out.printf("Berat badan: %.2f kg%n", beratBadan);

        // Mencetak tinggi badan menggunakan printf
        System.out.printf("Tinggi badan: %.2f cm%n", tinggiBadan);
    }
}
