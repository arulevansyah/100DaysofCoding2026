public class Day17 {
    public static void main(String[] args) {
        
        int angka = 10;

        // Operator penugasan = 
        angka = 20;
        System.out.println("Hasil = : " + angka);

        // Operator +=
        angka += 5;
        System.out.println("Hasil += : " + angka);

        // Operator -=
        angka -= 3;
        System.out.println("Hasil -= : " + angka);

        // Operator *=
        angka *= 2;
        System.out.println("Hasil *= : " + angka);

        // Operator /=
        angka /= 4;
        System.out.println("Hasil /= : " + angka);
        
        // Operator %=
        angka %= 3;
        System.out.println("Hasil %= : " + angka);
    }
}
