public class Day19 {
    public static void main(String[] args) {
        
        double nilaibesar = 100.00;

        float angkafloat = (float) nilaibesar;
        long angkalong = (long) nilaibesar;
        int angkaint = (int) nilaibesar;
        short angkashort = (short) nilaibesar;
        byte angkabyte = (byte) nilaibesar;

        System.out.println("Nilai double: " + nilaibesar);
        System.out.println("Nilai float: " + angkafloat);
        System.out.println("Nilai long: " + angkalong);
        System.out.println("Nilai int: " + angkaint);
        System.out.println("Nilai short: " + angkashort);
        System.out.println("Nilai byte: " + angkabyte);


    }
    
}
