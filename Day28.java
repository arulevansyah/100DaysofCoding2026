public class Day28 {
    public static void main(String[] args) {

        // Deklarasi
        int a = 10;
        int b = 10;
        int c = 10;
        int d = 20;

        // Operator perbandingan ==
        System.out.println("Operator Perbandingan ==");
        System.out.println("Hasil True\t: "  + (a == b));
        System.out.println("Hasil False\t: " + (c == d));

        // Operator perbandingan !=
        System.out.println("\nOperator Perbandingan !=");
        System.out.println("Hasil True\t: " + (a != d));
        System.out.println("Hasil False\t: " + (b != c));

    }
}
