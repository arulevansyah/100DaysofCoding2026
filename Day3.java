public class day3 {
    public static void main(String[] args) {
        // \n digunakan untuk pindah baris //
        System.out.print("==== BIODATA DIRI ====\n");

        // \t digunakan untuk memberikan jarak tab //
        System.out.print("Nama\t:Arul Evansyah\n");
        System.out.print("Umur\t:19\n");
        System.out.print("Prodi\t:Informatika\n");

        // \" digunakan untuk menampilkan tanda petik \" //
        System.out.println("Motto\t:\"Terus Belajar\"");

        // \\ digunakan untuk backslash //
        System.out.println("Folder\t:C:\\BelajarJava");
    }
}
