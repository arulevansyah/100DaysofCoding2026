public class day4 {
    public static void main(String[] args) {
        // Tipe data byte
        byte umur = 19;

        // Tipe data short
        short tahunlahir = 2007;

        // Tipe data int
        int jumlahuang = 100000;

        // Tipe data long
        long jumlahpendudukdunia = 8000000000L;

        // Menampilkan nilai variabel
        System.out.println("Umur: " + umur);
        System.out.println("Tahun Lahir: " + tahunlahir);
        System.out.println("Jumlah Uang: " + jumlahuang);
        System.out.println("Jumlah penduduk dunia: " + jumlahpendudukdunia);
    }
}
